#include "visca_packets.hpp"

#include <cassert>
#include <cstdint>
#include <vector>

using simplecam::ViscaPacket;

int main()
{
	assert(simplecam::makeHome(1) == ViscaPacket({0x81, 0x01, 0x06, 0x04, 0xFF}));
	assert(simplecam::makePanTilt(1, 7, 7, 0x03, 0x01) ==
	       ViscaPacket({0x81, 0x01, 0x06, 0x01, 0x07, 0x07, 0x03, 0x01, 0xFF}));
	assert(simplecam::makeStopPanTilt(1, 7, 7) ==
	       ViscaPacket({0x81, 0x01, 0x06, 0x01, 0x07, 0x07, 0x03, 0x03, 0xFF}));
	assert(simplecam::makeZoomDrive(1, true) == ViscaPacket({0x81, 0x01, 0x04, 0x07, 0x20, 0xFF}));
	assert(simplecam::makeZoomDrive(1, false) == ViscaPacket({0x81, 0x01, 0x04, 0x07, 0x30, 0xFF}));
	assert(simplecam::makeZoomStop(1) == ViscaPacket({0x81, 0x01, 0x04, 0x07, 0x00, 0xFF}));
	assert(simplecam::makeZoomPosition(1, 50) ==
	       ViscaPacket({0x81, 0x01, 0x04, 0x47, 0x01, 0x00, 0x01, 0x00, 0xFF}));
	assert(simplecam::makeZoomPosition(1, 200) ==
	       ViscaPacket({0x81, 0x01, 0x04, 0x47, 0x04, 0x00, 0x01, 0x00, 0xFF}));
	assert(simplecam::makePresetRecall(1, 15) == ViscaPacket({0x81, 0x01, 0x04, 0x3F, 0x02, 0x0F, 0xFF}));

	const auto store = simplecam::makePresetStoreSequence(1, 15);
	assert(store.size() == 3);
	assert(store[0] == ViscaPacket({0x81, 0x01, 0x04, 0x3F, 0x00, 0x0F, 0xFF}));
	assert(store[1] == ViscaPacket({0x81, 0x01, 0x04, 0x3F, 0x01, 0x0F, 0xFF}));
	assert(store[2] == ViscaPacket({0x81, 0x01, 0x7E, 0x01, 0x0B, 0x0F, 0x10, 0xFF}));
	assert(simplecam::makeBacklight(1, true) == ViscaPacket({0x81, 0x01, 0x04, 0x33, 0x02, 0xFF}));
	assert(simplecam::makeBacklight(1, false) == ViscaPacket({0x81, 0x01, 0x04, 0x33, 0x03, 0xFF}));
	assert(simplecam::makeManualFocus(1, true) == ViscaPacket({0x81, 0x01, 0x04, 0x38, 0x03, 0xFF}));
	assert(simplecam::makeManualFocus(1, false) == ViscaPacket({0x81, 0x01, 0x04, 0x38, 0x02, 0xFF}));
	assert(simplecam::makeFocusDrive(1, true) == ViscaPacket({0x81, 0x01, 0x04, 0x08, 0x03, 0xFF}));
	assert(simplecam::makeFocusDrive(1, false) == ViscaPacket({0x81, 0x01, 0x04, 0x08, 0x02, 0xFF}));
	assert(simplecam::makeFocusStop(1) == ViscaPacket({0x81, 0x01, 0x04, 0x07, 0x00, 0xFF}));
	assert(simplecam::makeExposureCompensation(1, true) == ViscaPacket({0x81, 0x01, 0x04, 0x33, 0x02, 0xFF}));
	assert(simplecam::makeExposureCompensation(1, false) == ViscaPacket({0x81, 0x01, 0x04, 0x33, 0x03, 0xFF}));
	assert(simplecam::makeCameraPower(1, true) == ViscaPacket({0x81, 0x01, 0x04, 0x00, 0x02, 0xFF}));
	assert(simplecam::makeCameraPower(1, false) == ViscaPacket({0x81, 0x01, 0x04, 0x00, 0x03, 0xFF}));

	return 0;
}
